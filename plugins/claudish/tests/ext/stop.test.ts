import { expect } from 'claude-code/testing'
import { test } from '../kit'
import { harness, start } from '../fake-claudish'
import { mountBand, SURFACES, walk } from '../ui'
import { POLL, button, delegate, drawingText, press, row, DARK, stateColor, team, textOf } from './support'

for (const surface of SURFACES) {
  test(`ext Stop: first press only arms, as a filled [ Stop? ] button, and expires at four seconds [${surface}]`, async ($, on) => {
    const h = harness(on)
    await start($, surface)
    const r = await team($, h)
    const b = await mountBand($, surface)
    const ink = (n: unknown) => walk(n).map(x => x.node).find(x => x.type === 'Text')?.props
    const unarmed = await b.find({ type: 'Button', text: /^\[ Stop \]$/ })
    expect(unarmed?.props.label).toBe('Stop')
    expect(ink(unarmed)).toMatchObject({ color: 'error', bold: true })
    expect(ink(unarmed)?.backgroundColor).toBeUndefined() // a button, no fill
    await press(b, 'model-a', 'Stop')
    expect(h.fake.cancelCalls()).toHaveLength(0)
    await b.redraw()
    const confirm = await b.find({ type: 'Button', text: /^\[ Stop\? \]$/ })
    expect(confirm?.props.label).toBe('Stop?')
    expect(confirm?.props.plain).toBe(true) // drawn by its own Text, not as a primary button
    expect(confirm?.props.variant).toBeUndefined()
    expect(ink(confirm)).toMatchObject({ color: 'inverseText', backgroundColor: 'error', bold: true })
    await h.clock.advance(3_999)
    await b.redraw()
    expect(textOf(await row(b, 'model-a'))).toContain('Stop?')
    await h.clock.advance(1)
    await b.redraw()
    expect(textOf(await row(b, 'model-a'))).not.toContain('Stop?')
    expect(await button(b, 'model-a', 'Stop')).toBeDefined()
    await h.clock.advance(1_000)
    expect(h.fake.cancelCalls()).toHaveLength(0)
    expect(r.slots.every(s => s.control.state === 'RUNNING')).toBe(true)
    await b.unmount()
  })

  test(`ext Stop: confirm targets exactly one slot and run id; stopped still wakes [${surface}]`, async ($, on) => {
    const h = harness(on)
    await start($, surface)
    const r = await team($, h)
    const b = await mountBand($, surface)
    await press(b, 'model-b', 'Stop')
    await b.redraw()
    await press(b, 'model-b', 'Stop?')
    expect(h.fake.cancelCalls()).toHaveLength(1)
    expect(h.fake.cancelCalls()[0]).toMatchObject({ tool: 'team', server: 'plugin:claudish:claudish', args: { mode: 'cancel', path: r.path, run_id: r.runId, slot: '02' } })
    expect(Object.keys(h.fake.cancelCalls()[0]!.args).sort()).toEqual(['mode', 'path', 'run_id', 'slot'])
    expect(r.slots.map(s => s.control.state)).toEqual(['RUNNING', 'CANCELLED', 'RUNNING'])
    await h.clock.advance(POLL)
    await b.redraw()
    stateColor(await row(b, 'model-b'), 'STP', DARK.snow, DARK.stopped)
    expect(walk(await row(b, 'model-b')).filter(x => x.node.type === 'Button' && x.node.props?.label === 'Stop')).toHaveLength(0)
    expect(h.submits).toHaveLength(1)
    expect(h.submits[0]).toContain('stopped by the person')
    await h.clock.advance(20_000)
    expect(h.fake.cancelCalls()).toHaveLength(1)
    expect(h.submits).toHaveLength(1)
    await b.unmount()
  })

  test(`ext Stop: delegation uses session_id, not a team or pane address [${surface}]`, async ($, on) => {
    const h = harness(on)
    await start($, surface)
    const s = await delegate($, h)
    const b = await mountBand($, surface)
    await press(b, s.model, 'Stop')
    await b.redraw()
    await press(b, s.model, 'Stop?')
    expect(h.fake.cancelCalls()).toHaveLength(1)
    expect(h.fake.cancelCalls()[0]).toMatchObject({ tool: 'cancel_session', args: { session_id: s.id } })
    expect(Object.keys(h.fake.cancelCalls()[0]!.args)).toEqual(['session_id'])
    await h.clock.advance(POLL + POLL)
    await b.redraw()
    stateColor(await row(b, s.model), 'STP', DARK.snow, DARK.stopped)
    expect(h.submits).toHaveLength(1)
    expect(h.submits[0]).toContain('stopped by the person')
    await b.unmount()
  })

  test(`ext Stop: concurrent confirm presses can send only one cancel [${surface}]`, async ($, on) => {
    const h = harness(on)
    await start($, surface)
    await team($, h)
    const b = await mountBand($, surface)
    await press(b, 'model-a', 'Stop')
    await b.redraw()
    const key = await button(b, 'model-a', 'Stop?')
    await Promise.all([b.press({ key }), b.press({ key })])
    expect(h.fake.cancelCalls()).toHaveLength(1)
    await b.unmount()
  })

  test(`ext Stop: arms are per slot; a press at the deadline starts a fresh arm [${surface}]`, async ($, on) => {
    const h = harness(on)
    await start($, surface)
    const r = await team($, h)
    const b = await mountBand($, surface)
    await press(b, 'model-a', 'Stop')
    await h.clock.advance(2_000)
    await b.redraw()
    await press(b, 'model-b', 'Stop')
    await h.clock.advance(2_000)
    await b.redraw()
    await press(b, 'model-a', 'Stop')
    expect(h.fake.cancelCalls()).toHaveLength(0)
    await b.redraw()
    expect(await b.findAll({ type: 'Button', text: /^\[ Stop\? \]$/ })).toHaveLength(2)
    await press(b, 'model-b', 'Stop?')
    expect(h.fake.cancelCalls().map(c => c.args.slot)).toEqual(['02'])
    expect(r.slots[0]!.control.state).toBe('RUNNING')
    await b.unmount()
  })

  for (const [name, options] of [
    ['ContractError', { cancelError: 'unknown_slot' }],
    ['permission denial', { denyCancel: 'person answered No' }],
  ] as const) {
    test(`ext Stop: ${name} clears confirmation and does not claim a person stop [${surface}]`, async ($, on) => {
      const h = harness(on, options)
      await start($, surface)
      const r = await team($, h)
      const b = await mountBand($, surface)
      await press(b, 'model-a', 'Stop')
      await b.redraw()
      await press(b, 'model-a', 'Stop?')
      await b.redraw()
      expect(await button(b, 'model-a', 'Stop')).toBeDefined()
      expect(h.toasts.some(t => /Stop failed/.test(t))).toBe(true)
      expect(r.slots[0]!.control.state).toBe('RUNNING')
      h.fake.set(r.runId, '01', 'CANCELLED', 'cancelled')
      await h.clock.advance(POLL)
      expect(h.submits).toHaveLength(1)
      expect(h.submits[0]).not.toContain('stopped by the person')
      await b.unmount()
    })
  }

  test(`ext Stop: changed:false cannot credit the person for an already-ended slot [${surface}]`, async ($, on) => {
    const h = harness(on)
    await start($, surface)
    const r = await team($, h)
    const b = await mountBand($, surface)
    await press(b, 'model-a', 'Stop')
    await b.redraw()
    // No poll between the outside cancellation and the person's second press.
    h.fake.set(r.runId, '01', 'CANCELLED', 'cancelled')
    await press(b, 'model-a', 'Stop?')
    expect(h.fake.cancelCalls()).toHaveLength(1)
    await h.clock.advance(POLL)
    expect(h.submits).toHaveLength(1)
    expect(h.submits[0]).not.toContain('stopped by the person')
    await b.unmount()
  })

  test(`ext Stop: held permission/cancel answer cannot send twice or time out [${surface}]`, async ($, on) => {
    const h = harness(on)
    await start($, surface)
    await team($, h)
    const b = await mountBand($, surface)
    await press(b, 'model-a', 'Stop')
    await b.redraw()
    const key = await button(b, 'model-a', 'Stop?')
    const gate = h.fake.holdCancels()
    const pending = b.press({ key })
    await h.clock.settle()
    expect(h.fake.cancelCalls()).toHaveLength(1)
    await h.clock.advance(25_000)
    await b.redraw()
    expect(textOf(await row(b, 'model-a'))).not.toContain('Stop?')
    expect(walk(await row(b, 'model-a')).some(x => x.node.type === 'Button' && x.node.props?.label === 'Stop')).toBe(false)
    expect(h.toasts.some(t => /Stop not confirmed/.test(t))).toBe(false)
    gate.release()
    await pending
    await h.clock.advance(POLL)
    await b.redraw()
    expect(await drawingText(b)).toContain(' STP ')
    expect(h.fake.cancelCalls()).toHaveLength(1)
    await b.unmount()
  })

  test(`ext Stop: absent cancel capability offers no Stop, but keeps Show [${surface}]`, async ($, on) => {
    const h = harness(on, { noCancel: true })
    await start($, surface)
    await team($, h)
    const b = await mountBand($, surface)
    expect(await b.findAll({ type: 'Button', text: /^\[ Stop \]$/ })).toHaveLength(0)
    expect(await b.findAll({ type: 'Button', text: /^\[ Show \]$/ })).toHaveLength(3)
    expect(h.fake.cancelCalls()).toHaveLength(0)
    await b.unmount()
  })
}
